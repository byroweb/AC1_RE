"""gen_exe.py: generate the splat config for the resident exe (full-link P1).

Reads overlays/CODE_UNITS.tsv and tools/loop/functions.tsv, and the retail exe carved
from your own disc (AC1_BIN, the same carve match_fn.py uses). Writes, under
build/link/exe/:
  image.bin          the exe without its 0x800-byte PS-X EXE header (splat's input)
  exe.yaml           splat config: one asm file per function, rodata/data as retail slices (T0)
  symbol_addrs.txt   function names from functions.tsv

The header is not split: tools/link/mkpsexe.py generates it after the link.
"""
import argparse, collections, csv, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "tools", "match"))
import match_fn  # noqa: E402  (carve_exe, VENDOR)

EXE_HEADER = 0x800
EXE_BSS_START = 0x80039CB8   # __SN_ENTRY_POINT zeroes [0x80039CB8, 0x8004ADA0)
EXE_BSS_END = 0x8004ADA0     # = the program-overlay base


def code_unit(unit):
    with open(os.path.join(ROOT, "overlays", "CODE_UNITS.tsv"), newline="") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            if r["unit"] == unit:
                return r
    raise SystemExit("no CODE_UNITS.tsv row for %s" % unit)


def functions(unit):
    with open(os.path.join(ROOT, "tools", "loop", "functions.tsv"), newline="") as fh:
        rows = [r for r in csv.DictReader(fh, delimiter="\t") if r["unit"] == unit]
    return sorted(rows, key=lambda r: int(r["vaddr"], 16))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "link", "exe"))
    args = ap.parse_args()
    out = args.out
    os.makedirs(out, exist_ok=True)

    cu = code_unit("SCUS_941.82")
    vram = int(cu["vram"], 16)
    rodata_off, text_off, data_off = (int(cu[k], 16) for k in ("rodata_off", "text_off", "data_off"))
    text_va, data_va = int(cu["text_va"], 16), int(cu["data_va"], 16)
    assert rodata_off == EXE_HEADER and text_va == vram + text_off - EXE_HEADER

    exe = open(match_fn.carve_exe(os.path.join(match_fn.VENDOR, "cache")), "rb").read()
    image = exe[EXE_HEADER:]
    open(os.path.join(out, "image.bin"), "wb").write(image)
    data_end = EXE_BSS_START - vram           # image offset where .data ends

    funcs = functions("exe")
    if int(funcs[0]["vaddr"], 16) != text_va:
        raise SystemExit("first exe function is not at text_va 0x%08X" % text_va)

    # Names: functions.tsv, with duplicates (PsyQ links a few modules twice) made unique by address.
    count = collections.Counter(r["name"] for r in funcs)
    names = {}
    for r in funcs:
        va = int(r["vaddr"], 16)
        n = r["name"]
        if not re.match(r"[A-Za-z_][A-Za-z0-9_]*$", n):   # e.g. 2MBYTE_OBJ_B4: not an assembler symbol
            n = "func_%08X" % va
        names[va] = n if count[n] == 1 else "%s_%08X" % (n, va)
    with open(os.path.join(out, "symbol_addrs.txt"), "w", newline="\n") as fh:
        for va, n in sorted(names.items()):
            fh.write("%s = 0x%08X; // type:func\n" % (n, va))

    sub = ["      - [0x0, rodatabin, rodata]   # T0: retail .rodata slice (P5 symbolises it)"]
    for r in funcs:
        va = int(r["vaddr"], 16)
        sub.append("      - [0x%X, asm, f_%08X]" % (va - vram, va))
    sub.append("      - [0x%X, databin, data]   # T0: retail .data slice" % (data_va - vram))
    sub.append("      - { start: 0x%X, type: bss, vram: 0x%08X }" % (data_end, EXE_BSS_START))

    # Every path is relative to the output directory, where make runs as and ld.
    yaml = """# Generated by tools/link/gen_exe.py: do not edit.
name: SLUS_013.23 image
options:
  basename: ac1_exe
  base_path: .
  target_path: image.bin
  platform: psx
  compiler: GCC
  build_path: obj
  asm_path: asm
  src_path: src
  asset_path: bin
  ld_script_path: exe.ld
  ld_legacy_generation: False
  symbol_addrs_path: [symbol_addrs.txt]
  undefined_funcs_auto_path: undefined_funcs_auto.txt
  undefined_syms_auto_path: undefined_syms_auto.txt
  section_order: [".rodata", ".text", ".data", ".bss"]
  find_file_boundaries: False
  disassemble_all: True
  create_c_files: False
  generate_asm_macros_files: True
  asm_inc_header: ""
  subalign: 4
  ld_bss_is_noload: True
  ld_bss_contains_common: True
  ld_align_segment_vram_end: False
  ld_align_section_vram_end: False
  segment_end_before_align: True
segments:
  - name: main
    type: code
    start: 0x0
    vram: 0x{vram:08X}
    bss_size: 0x{bss:X}
    subsegments:
{sub}
  - [0x{end:X}]
""".format(vram=vram, bss=EXE_BSS_END - EXE_BSS_START, sub="\n".join(sub), end=data_end)
    open(os.path.join(out, "exe.yaml"), "w", newline="\n").write(yaml)
    print("exe: %d functions, image 0x%X bytes (.data ends at 0x%X), bss 0x%08X..0x%08X"
          % (len(funcs), len(image), data_end, EXE_BSS_START, EXE_BSS_END))


if __name__ == "__main__":
    main()
